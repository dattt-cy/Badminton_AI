"""Compare Random Forest vs R(2+1)D hit detector results side by side.

Reads the output JSON files from evaluate_shuttleset_hit_spotting.py (RF)
and evaluate_rgb_hit_spotting.py (R(2+1)D) and prints a markdown comparison
table at each tolerance level.

Usage:
    python scripts/evaluation/compare_hit_detectors.py \\
        --rf outputs/hit_rf_test.json \\
        --rgb outputs/hit_rgb_test.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rf", type=Path, required=True,
                        help="JSON output from evaluate_shuttleset_hit_spotting.py (RF model).")
    parser.add_argument("--rgb", type=Path, required=True,
                        help="JSON output from evaluate_rgb_hit_spotting.py (R(2+1)D model).")
    parser.add_argument("--tolerances", type=int, nargs="+", default=[2, 5, 15],
                        help="Frame tolerances to compare (default: 2 5 15).")
    return parser.parse_args()


def _fmt(value: float | None, pct: bool = True) -> str:
    if value is None:
        return "—"
    return f"{value * 100:.1f}%" if pct else f"{value:.1f}"


def main() -> None:
    args = parse_args()

    rf_data = json.loads(args.rf.read_text(encoding="utf-8"))
    rgb_data = json.loads(args.rgb.read_text(encoding="utf-8"))

    rf_metrics = rf_data.get("metrics_by_tolerance", rf_data.get("metrics", {}))
    rgb_metrics = rgb_data.get("metrics_by_tolerance", {})

    print(f"\n## Hit Detector Comparison — Split: {rgb_data.get('split', '?')}\n")
    print(f"**RF model:** `{args.rf.name}`  threshold={rf_data.get('selected_threshold', rf_data.get('best_threshold', '?'))}")
    print(f"**R(2+1)D model:** `{args.rgb.name}`  threshold={rgb_data.get('selected_threshold', '?')}")
    print(f"**Matches evaluated:** {rgb_data.get('match_ids', [])}\n")

    # Header
    header = "| Tolerance | Model | Precision | Recall | F1 | TP | FP | FN | Side Acc | Mean Err |"
    sep = "|---|---|---|---|---|---|---|---|---|---|"
    print(header)
    print(sep)

    for tol in args.tolerances:
        tol_key = str(tol)
        rf_m = rf_metrics.get(tol_key, {})
        rgb_m = rgb_metrics.get(tol_key, {})

        for model_name, m in [("RF (motion)", rf_m), ("R(2+1)D", rgb_m)]:
            if not m:
                print(f"| ±{tol} | {model_name} | — | — | — | — | — | — | — | — |")
                continue
            print(
                f"| ±{tol} | {model_name} "
                f"| {_fmt(m.get('precision'))} "
                f"| {_fmt(m.get('recall'))} "
                f"| **{_fmt(m.get('f1'))}** "
                f"| {m.get('true_positives', '?')} "
                f"| {m.get('false_positives', '?')} "
                f"| {m.get('false_negatives', '?')} "
                f"| {_fmt(m.get('side_accuracy'))} "
                f"| {_fmt(m.get('mean_absolute_frame_error'), pct=False)} |"
            )

    # Per-match breakdown for primary tolerance (±5)
    print(f"\n### Per-match breakdown (±5 frames)\n")
    tol5_rgb = rgb_metrics.get("5", {})
    tol5_rf = rf_metrics.get("5", {})

    per_match_rgb = tol5_rgb.get("per_match", {})
    per_match_rf = tol5_rf.get("per_match", {})
    all_ids = sorted(set(per_match_rgb) | set(per_match_rf), key=lambda x: int(x))

    print("| Match | Truth | RF TP | RF F1 | R(2+1)D TP | R(2+1)D F1 |")
    print("|---|---|---|---|---|---|")
    for mid in all_ids:
        rf_pm = per_match_rf.get(mid, {})
        rgb_pm = per_match_rgb.get(mid, {})
        print(
            f"| {mid} "
            f"| {rf_pm.get('truth', rgb_pm.get('truth', '?'))} "
            f"| {rf_pm.get('true_positives', '?')} "
            f"| {_fmt(rf_pm.get('f1'))} "
            f"| {rgb_pm.get('true_positives', '?')} "
            f"| {_fmt(rgb_pm.get('f1'))} |"
        )

    print("\n> Generated by `compare_hit_detectors.py`")


if __name__ == "__main__":
    main()

